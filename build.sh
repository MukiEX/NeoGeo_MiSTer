#!/bin/sh
# Build PaddleNeoGeo in an isolated snapshot with Docker / Quartus 17.0 Lite.
# Usage: ./build.sh [--seed X] [--dual] [--allow-timing-fail] [--result-file PATH]
#   --seed X              override the fitter seed (default: keep the QSF's seed)
#   --dual                build the NeoGeo_DualSDR revision instead of NeoGeo
#   --allow-timing-fail   still pass (with a warning) if timing is not met
#   --result-file PATH    on a passing build, write the final RBF's path to PATH (for CI)
# Every run also writes build-info.txt (commit, seed, utilization, slack, md5) beside the RBF.
# Exit codes: 0 pass, 2 bad arguments, 4 timing not met, anything else = build/setup failure.
# Each run keeps its project, progress log and results in builds/run.XXXXXX/.
# Concurrent runs (including repeated seeds) never modify the source checkout.
# Budget RAM for every concurrent Quartus process; plan on ~8 GB each.
set -e

usage() {
    echo "Usage: $0 [--seed X] [--dual] [--allow-timing-fail] [--result-file PATH]"
    echo "X is a non-negative decimal integer; Quartus enforces its supported range."
}

SEED=""
PROJECT=NeoGeo
ALLOW_TIMING_FAIL=0
RESULT_FILE=""
while [ "$#" -gt 0 ]; do
    case "$1" in
        --seed)
            [ "$#" -ge 2 ] || { usage >&2; exit 2; }
            case "$2" in
                ''|*[!0-9]*) echo "Invalid seed: $2" >&2; usage >&2; exit 2 ;;
            esac
            SEED=$2
            shift 2
            ;;
        --dual) PROJECT=NeoGeo_DualSDR; shift ;;
        --allow-timing-fail) ALLOW_TIMING_FAIL=1; shift ;;
        --result-file)
            [ "$#" -ge 2 ] && [ -n "$2" ] || { usage >&2; exit 2; }
            case "$2" in /*) RESULT_FILE=$2 ;; *) RESULT_FILE=$(pwd -P)/$2 ;; esac
            shift 2
            ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
done

case "$PROJECT" in
    NeoGeo)         OUT_NAME=PaddleNeoGeo ;;
    NeoGeo_DualSDR) OUT_NAME=PaddleNeoGeo_DualSDR ;;
esac

cd "$(dirname "$0")"
SOURCE_DIR=$(pwd -P)
[ -f "$SOURCE_DIR/$PROJECT.qsf" ] || { echo "Missing $PROJECT.qsf in $SOURCE_DIR" >&2; exit 1; }
mkdir -p "$SOURCE_DIR/builds"
RUN_DIR=$(mktemp -d "$SOURCE_DIR/builds/run.XXXXXX")
PROJECT_DIR="$RUN_DIR/project"
LOG="$RUN_DIR/progress.log"
STAMP=$(date +%Y%m%d)
mkdir "$PROJECT_DIR"
INFO="$RUN_DIR/build-info.txt"
echo "Project: $PROJECT"
echo "Build directory: $RUN_DIR"

# Record which source this build came from. "-dirty" marks uncommitted local edits.
COMMIT=unknown
if git -C "$SOURCE_DIR" rev-parse --git-dir >/dev/null 2>&1; then
    COMMIT=$(git -C "$SOURCE_DIR" rev-parse HEAD)
    [ -z "$(git -C "$SOURCE_DIR" status --porcelain --untracked-files=no)" ] || COMMIT="$COMMIT-dirty"
fi
echo "Commit: $COMMIT"

# Copy working files, including local edits, but exclude generated build state.
# Archive first so a failed copy cannot be hidden by a successful pipeline stage.
# Excluding builds also prevents copying this and other concurrent snapshots;
# releases/ only holds prebuilt RBFs and romset XMLs, which the build never reads.
tar --exclude='./.git' --exclude='./builds' --exclude='./db' \
    --exclude='./incremental_db' --exclude='./output_files' \
    --exclude='./releases' --exclude='./sim' \
    -cf "$RUN_DIR/source.tar" -C "$SOURCE_DIR" .
tar -xf "$RUN_DIR/source.tar" -C "$PROJECT_DIR"
rm -f "$RUN_DIR/source.tar"
cd "$PROJECT_DIR"

# With --seed, replace all existing seed assignments in this snapshot's QSF.
if [ -n "$SEED" ]; then
    sed '/^[[:space:]]*set_global_assignment[[:space:]]*-name[[:space:]]*SEED[[:space:]]/d' \
        "$PROJECT.qsf" > "$PROJECT.qsf.tmp"
    printf '\nset_global_assignment -name SEED %s\n' "$SEED" >> "$PROJECT.qsf.tmp"
    mv "$PROJECT.qsf.tmp" "$PROJECT.qsf"
    echo "Seed: $SEED"
else
    SEED=$(sed -n 's/^[[:space:]]*set_global_assignment[[:space:]]*-name[[:space:]]*SEED[[:space:]]*\([0-9]*\).*/\1/p' "$PROJECT.qsf" | tail -1)
    echo "Seed: $SEED (from $PROJECT.qsf)"
fi
{
    echo "Project:  $PROJECT"
    echo "Commit:   $COMMIT"
    echo "Seed:     $SEED"
    echo "Built:    $(date -u '+%Y-%m-%d %H:%M UTC')"
} > "$INFO"
# build_id.v is generated by sys/build_id.tcl as Quartus' pre-flow script.

# A unique container lets interruption stop only this invocation's build.
CONTAINER="paddleneogeo-$(basename "$RUN_DIR")"
BUILD_PID=""
cleanup() {
    if [ -n "$BUILD_PID" ]; then
        docker rm -f "$CONTAINER" >/dev/null 2>&1 || :
        wait "$BUILD_PID" 2>/dev/null || :
    fi
}
trap cleanup 0
trap 'exit 130' INT
trap 'exit 143' TERM

# Match the invoking user so bind-mounted outputs are not owned by root.
# Quartus may write user settings; give this numeric UID a writable HOME.
mkdir -p "$PROJECT_DIR/.build-home"
# Archives can carry restrictive modes; the snapshot only needs to be ours and writable.
chmod -R u+rwX "$PROJECT_DIR"

IMAGE=theypsilon/quartus-lite-c5:17.0.2
# :z gives the snapshot an SELinux label containers may write (no-op without SELinux).
# It only relabels this run's private copy, never the source checkout.
MOUNT="$PROJECT_DIR:/project:z"

# Probe write access first so a mount problem fails fast with a clear reason.
if ! docker run --rm --user "$(id -u):$(id -g)" -v "$MOUNT" -w /project "$IMAGE" \
        sh -c 'mkdir /project/.probe && rmdir /project/.probe' > "$RUN_DIR/probe.log" 2>&1; then
    echo "GATE FAIL: the container cannot write to the snapshot directory."
    cat "$RUN_DIR/probe.log"
    echo
    echo "Host side:      $(ls -ldn "$PROJECT_DIR")   (you are uid $(id -u), gid $(id -g))"
    docker run --rm --user "$(id -u):$(id -g)" -v "$MOUNT" "$IMAGE" \
        sh -c 'echo "Container side: $(ls -ldn /project)   (running as $(id -u):$(id -g))"' 2>&1 || :
    docker info --format 'Docker security options: {{.SecurityOptions}}' 2>/dev/null || :
    echo "If the owner IDs differ between the two sides, Docker is running rootless (user namespace)."
    echo "If they match, check SELinux/AppArmor denials: sudo ausearch -m avc -ts recent"
    exit 1
fi

docker run --rm --name "$CONTAINER" --user "$(id -u):$(id -g)" \
    -e HOME=/project/.build-home -v "$MOUNT" \
    -w /project "$IMAGE" \
    quartus_sh --flow compile "$PROJECT" > "$LOG" 2>&1 &
BUILD_PID=$!

# Progress monitor: watch the log for phase transitions
START=$(date +%s)
LAST_PHASE=""
LAST_PRINT=0
while kill -0 "$BUILD_PID" 2>/dev/null; do
    NOW=$(date +%s)
    ELAPSED=$((NOW - START))
    MINS=$((ELAPSED / 60))
    SECS=$((ELAPSED % 60))

    # Determine current phase from the log (17.0 calls STA "TimeQuest")
    if grep -Eq "TimeQuest|Timing Analy" "$LOG" 2>/dev/null; then
        PHASE="sta";   PCT=95
    elif grep -q "Assembler" "$LOG" 2>/dev/null; then
        PHASE="asm";   PCT=85
    elif grep -q "Fitter" "$LOG" 2>/dev/null; then
        PHASE="fit";   PCT=60
    elif grep -q "Analysis & Synthesis" "$LOG" 2>/dev/null; then
        PHASE="map";   PCT=20
    elif grep -q "Quartus Prime Shell" "$LOG" 2>/dev/null; then
        PHASE="start"; PCT=5
    else
        PHASE="init";  PCT=0
    fi

    # Only print when the phase changes, or every 15s as a heartbeat
    if [ "$PHASE" != "$LAST_PHASE" ] || [ $((ELAPSED - LAST_PRINT)) -ge 15 ]; then
        printf "[%02d:%02d] %-6s ~%d%%\n" "$MINS" "$SECS" "$PHASE" "$PCT"
        LAST_PHASE="$PHASE"
        LAST_PRINT=$ELAPSED
    fi
    sleep 1
done

RC=0
wait "$BUILD_PID" || RC=$?
BUILD_PID=""

echo
echo "build exited with rc=$RC"
if [ "$RC" -ne 0 ]; then
    # The tail is only Quartus' summary; show the actual errors and their context.
    echo "Errors (full log: $LOG):"
    grep -n -B2 -A3 -E "^(Error|Critical Warning)|ERROR:|can't|couldn't" "$LOG" | head -60 || tail -40 "$LOG"
    for r in "$PROJECT_DIR"/output_files/*.rpt "$PROJECT_DIR"/*.rpt; do
        [ -f "$r" ] && grep -H -n -E "^(Error|Critical Warning)" "$r" | head -20
    done
    exit "$RC"
fi
tail -5 "$LOG"

RBF=output_files/$PROJECT.rbf
RPT=output_files/$PROJECT.sta.rpt
FIT=output_files/$PROJECT.fit.summary
[ -f "$RBF" ] || { echo "GATE FAIL: no rbf produced"; exit 1; }
[ -f "$RPT" ] || { echo "GATE FAIL: no sta.rpt"; exit 1; }

# Resource usage, so headroom is visible on every run
if [ -f "$FIT" ]; then
    echo
    grep -E "Logic utilization|Total registers|Total block memory bits|Total RAM Blocks|Total DSP Blocks|Total pins" "$FIT" | tee -a "$INFO" || :
fi
grep -E "Worst-case (setup|hold) slack" "$RPT" | head -4 >> "$INFO" || :

OUT="$RUN_DIR/${OUT_NAME}_${STAMP}.rbf"
cp "$RBF" "$OUT"

finish() {
    echo "MD5:      $(md5sum "$OUT" | cut -d' ' -f1)" >> "$INFO"
    md5sum "$OUT"
    [ -z "$RESULT_FILE" ] || echo "$OUT" > "$RESULT_FILE"
    exit 0
}
echo
echo "RBF: $OUT"

if grep -q "Timing requirements not met" "$RPT"; then
    echo "WARNING: timing not met:"
    grep -E "Worst-case (setup|hold) slack" "$RPT" | head -4 || :
    if [ "$ALLOW_TIMING_FAIL" -eq 1 ]; then
        echo "GATE PASS (with timing warning, --allow-timing-fail)"
        echo "Timing:   NOT MET (built with --allow-timing-fail)" >> "$INFO"
        finish
    fi
    echo "Timing:   not met" >> "$INFO"
    echo "GATE FAIL: timing not met. Try another --seed, or rerun with --allow-timing-fail for a test build."
    exit 4
fi

echo "GATE PASS: timing met."
echo "Timing:   met" >> "$INFO"
finish
